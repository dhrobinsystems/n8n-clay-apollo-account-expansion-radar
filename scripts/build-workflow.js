  return [{ json: { kind: 'run_summary', source: 'apollo', status: 'ENGINE_ERROR', sandbox: config.sandboxMode, runId, error: Radar.redact(err && err.message ? err.message : String(err)), counts: {}, skipped: {}, errors: [], accounts: [] } }];
